"""Registered multi-model replication (GPU). See replication/protocol.json.

Phases, each resumable from its own files:
  1 histories  - the v2.1 candidate cases, three history turns generated by THIS model, admitted by the v2.1 rule check
  2 baseline   - B and C answers for ordinary and change requests; last-prompt-token states at eight depths (+ C_qa, C_json)
  3 directions - cross-fitted mean (B - C) at the steering depth; full-sample means at every depth; random controls
  4 steering   - C+mean, C-mean, C+random, B-mean on every admitted history and request type; teacher-forced KL
  5 open       - the 81 open transfer units: assistant turns regenerated by THIS model, then the same six conditions
"""
import argparse
import hashlib
import json
import os
import sys
import time
import traceback
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / 'replication'))
sys.path.insert(0, str(ROOT / 'intervention'))
from confirmation.common import append, check_rule, read, request_text, rows, sha, write
from engine import FAMILIES, Engine, depth_layers

RULES = ['combination:two_responses', 'format:json_format', 'format:bullet_list', 'startend:end_phrase']
TF = {'B': ['C', 'C_plus_mean', 'C_minus_mean', 'C_plus_random'], 'C': ['B', 'B_minus_mean']}


def now():
    return datetime.now(timezone.utc).isoformat()


def save_json(path, obj):
    tmp = Path(str(path) + '.tmp')
    tmp.write_text(json.dumps(obj, ensure_ascii=False), encoding='utf-8')
    os.replace(tmp, path)


def gen_record(e, g, rtype=None, case=None, word_limit=200):
    text = e.text(g['token_ids'])
    rec = dict(text=text, termination=g['termination'], n=max(1, len(g['token_ids'])), seconds=g['seconds'],
               generated_ids=g['generated_ids'], token_ids=g['token_ids'], truncated=g['truncated'])
    if case is not None:
        rec['score'] = check_rule(text, rtype, g['termination'] != 'turn_end', word_limit, case['inst_name'], case['inst_args'])
    return rec


def steered_unit(e, ids, base, vec, layer, cap, case=None, rtype=None):
    """ids = {'B','C'} prompt IDs; base = {'B','C'} unsteered generation records; vec = mean/random vectors."""
    from steer import Steer
    plan = {'C_plus_mean': ('C', vec['mean']), 'C_minus_mean': ('C', -vec['mean']), 'C_plus_random': ('C', vec['random']),
            'B_minus_mean': ('B', -vec['mean'])}
    gens = dict(base)
    for name, (form, v) in plan.items():
        with Steer(e.model, layer, v) as st:
            g = e.generate(ids[form], cap, st)
        assert st.calls[0] == (len(ids[form]), len(ids[form]) - 1) and all(c == (1, 0) for c in st.calls[1:])
        gens[name] = gen_record(e, g, rtype, case)
    for g in gens.values():
        g['exact_vs_B'] = g['generated_ids'] == gens['B']['generated_ids']
        g['exact_vs_C'] = g['generated_ids'] == gens['C']['generated_ids']
    conds = {'B': ('B', None), 'C': ('C', None), **plan}
    tf = {}
    for ref, members in TF.items():
        reference = gens[ref]['generated_ids']
        with Steer(e.model, layer, None) as st:
            ref_logp = e.tf_logprobs(ids[ref], reference, st)
        tf[ref] = {}
        for name in members:
            form, v = conds[name]
            with Steer(e.model, layer, v) as st:
                logp = e.tf_logprobs(ids[form], reference, st)
            if v is not None:
                assert st.calls == [(len(ids[form]) + len(reference) - 1, len(ids[form]) - 1)]
            tf[ref][name] = e.kl_summary(ref_logp, logp, reference)
            del logp
        del ref_logp
    return gens, tf


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--family', choices=sorted(FAMILIES), required=True)
    p.add_argument('--model', type=Path, required=True)
    p.add_argument('--v21', type=Path, required=True, help='extracted confirmation-v2_1 run folder (cases, protocol)')
    p.add_argument('--open-units', type=Path, required=True)
    p.add_argument('--registration', type=Path, required=True)
    p.add_argument('--protocol', type=Path, default=ROOT / 'replication/protocol.json')
    p.add_argument('--out', type=Path, required=True)
    p.add_argument('--resume', action='store_true')
    p.add_argument('--smoke', type=int, default=0, help='tiny-model smoke test: N cases per rule, every history admitted, cap 8')
    a = p.parse_args()
    cfg = read(a.protocol)
    if a.smoke:
        reg = dict(status='smoke_test_not_registered')
    else:
        reg = read(a.registration)
        assert cfg['status'] == 'reviewed' and reg['status'] == 'registered_before_generation'
        assert sha(a.protocol) == reg['protocol_sha256'] and sha(a.open_units) == reg['open_units_sha256']
        for f, d in reg['code_sha256'].items():
            assert sha(ROOT / f) == d, f'code changed after registration: {f}'
        for f, d in reg['v21_sha256'].items():
            assert sha(a.v21 / f) == d, f
    out = a.out
    if a.resume:
        assert out.is_dir() and read(out / 'registration.json') == reg
        append(out / 'restarts.jsonl', dict(utc=now()))
    else:
        assert not out.exists(), 'Use a new run directory'
        for d in ('activations', 'baseline', 'units', 'open_units'):
            (out / d).mkdir(parents=True)
        write(out / 'registration.json', reg)
        write(out / 'protocol.json', cfg)
    status = lambda **k: write(out / 'status.json', dict(utc=now(), family=a.family, **k))
    import torch
    try:
        status(phase='loading')
        if not a.smoke and not (out / 'model_files.json').exists():
            write(out / 'model_files.json', {f.name: sha(f) for f in sorted(a.model.iterdir()) if f.is_file() and f.suffix in ('.safetensors', '.json', '.model')})
        e = Engine(a.model, a.family)
        layers = depth_layers(e.n_layers)
        steer_layer, shallow_layer = layers[4], layers[2]
        cap = 8 if a.smoke else cfg['cap']
        if not (out / 'environment.json').exists():
            write(out / 'environment.json', dict(family=a.family, n_layers=e.n_layers, hidden=e.hidden, capture_layers=layers, steer_layer=steer_layer,
                                                 shallow_layer=shallow_layer, stop_ids=sorted(e.stop), turn_end=e.turn_end, system_prompt=e.spec['system'],
                                                 attn=e.spec['attn'], torch=torch.__version__, transformers=__import__('transformers').__version__,
                                                 device=torch.cuda.get_device_name(0) if e.device == 'cuda' else 'cpu', cap=cap))
        v21cfg = read(a.v21 / 'protocol.json')
        cases = rows(a.v21 / 'cases.jsonl')
        if a.smoke:
            cases = [c for r in RULES for c in [c for c in cases if c['inst_name'] == r][:a.smoke]]

        # ---- phase 1: histories
        done = {r['case_id'] for r in rows(out / 'case_status.jsonl')} if (out / 'case_status.jsonl').exists() else set()
        accepted = {r: 0 for r in RULES}
        for h in (rows(out / 'histories.jsonl') if (out / 'histories.jsonl').exists() else []):
            accepted[h['inst_name']] += 1
        target = a.smoke or v21cfg['target_per_rule']  # 30 per rule, as in v2.1 (protocol phase1_histories.admission)
        t0 = time.perf_counter()
        for c in cases:
            if c['case_id'] in done:
                continue
            if accepted[c['inst_name']] >= target:
                append(out / 'case_status.jsonl', dict(case_id=c['case_id'], source_id=c['source_id'], status='unused_reserve'))
                continue
            status(phase='histories', case_id=c['case_id'], accepted=accepted, seconds=time.perf_counter() - t0)
            history, scores, reason = [], [], None
            for i, q in enumerate(c['history_questions']):
                u = (c['rule_text'] + '\n\n' if i == 0 else '') + q
                ids = e.prompt(history, u, 'B')
                g = e.generate(ids, cap)
                r = gen_record(e, g)
                s = check_rule(r['text'], 'ordinary', g['termination'] != 'turn_end', v21cfg['word_limit'], c['inst_name'], c['inst_args'])
                append(out / 'history_attempts.jsonl', dict(case_id=c['case_id'], source_id=c['source_id'], turn=i, score=s, prompt_tokens=len(ids),
                                                            **{k: r[k] for k in ('text', 'termination', 'n', 'seconds')}))
                if not a.smoke:
                    if g['termination'] != 'turn_end' or set(g['token_ids']) & e.special:
                        reason = 'invalid_history'
                    elif not s['passed']:
                        reason = 'rule_not_established'
                if reason:
                    append(out / 'case_status.jsonl', dict(case_id=c['case_id'], source_id=c['source_id'], status=reason, turn=i))
                    break
                scores.append(s)
                history += [dict(role='user', content=u), dict(role='assistant', content=r['text'])]
            if reason:
                continue
            accepted[c['inst_name']] += 1
            append(out / 'histories.jsonl', dict(**c, history=history, history_scores=scores, established=True))
            append(out / 'case_status.jsonl', dict(case_id=c['case_id'], source_id=c['source_id'], status='admitted'))
        H = {h['source_id']: h for h in rows(out / 'histories.jsonl')}
        write(out / 'admission.json', dict(accepted=accepted, admitted=len(H), candidates_used=len({r['case_id'] for r in rows(out / 'case_status.jsonl')})))
        sources = sorted(H)

        # ---- phase 2: baseline answers and states
        def prompts(h, rtype):
            q = request_text(h['question'], rtype, 'B', v21cfg, h)
            ids = {f: e.prompt(h['history'], q, f) for f in ('B', 'C', 'C_qa', 'C_json')}
            assert len({ids[f][-1] for f in ids}) == 1
            return ids
        for s in sources:
            path = out / 'baseline' / f'{s}.json'
            if path.exists():
                continue
            status(phase='baseline', source_id=s, done=len(list((out / 'baseline').glob('*.json'))), total=len(sources))
            h, rec, acts = H[s], {}, []
            for rtype in ('ordinary', 'change'):
                ids = prompts(h, rtype)
                rec[rtype] = {}
                for form in ('B', 'C'):
                    g = e.generate(ids[form], cap, capture=layers)
                    rec[rtype][form] = dict(prompt_tokens=len(ids[form]), **gen_record(e, g, rtype, h))
                    for L, v in g['states'].items():
                        acts.append(dict(source_id=s, request_type=rtype, condition=form, layer=L, n_tokens=len(ids[form]), vector=v))
                if rtype == 'ordinary':
                    for form in ('C_qa', 'C_json'):
                        for L, v in e.states(ids[form], layers).items():
                            acts.append(dict(source_id=s, request_type=rtype, condition=form, layer=L, n_tokens=len(ids[form]), vector=v))
            torch.save(dict(records=acts, layers=layers), out / 'activations' / f'{s}.pt')
            save_json(path, rec)
            if e.device == 'cuda':
                torch.cuda.empty_cache()

        # ---- phase 3: directions
        dpath = out / 'directions.pt'
        if not dpath.exists():
            status(phase='directions')
            D = {}
            for s in sources:
                st = {(r['request_type'], r['condition'], r['layer']): r['vector'].double() for r in torch.load(out / 'activations' / f'{s}.pt', weights_only=True)['records']}
                D[s] = {L: st['ordinary', 'B', L] - st['ordinary', 'C', L] for L in layers}
            order = sorted(sources, key=lambda s: hashlib.sha256((s + 'replication-v1').encode()).hexdigest())
            fold = {s: i % 5 for i, s in enumerate(order)}
            vec = {}
            for i, s in enumerate(sources):
                others = [x for x in sources if fold[x] != fold[s]] or [x for x in sources if x != s] or [s]
                m = torch.stack([D[x][steer_layer] for x in others]).mean(0)
                g = torch.Generator().manual_seed(cfg['seed'] + i)
                r = torch.randn(m.numel(), generator=g, dtype=torch.float64)
                vec[s] = dict(mean=m.float(), random=(r / r.norm() * m.norm()).float())
            full = {L: torch.stack([D[s][L] for s in sources]).mean(0).float() for L in layers}
            torch.save(dict(steer_layer=steer_layer, layers=layers, folds=fold, vectors=vec, full_mean=full), dpath)
        dirs = torch.load(dpath, weights_only=True)

        # ---- phase 4: steering on the v2.1-style histories
        for s in sources:
            for rtype in ('ordinary', 'change'):
                path = out / 'units' / f'{s}_{rtype}.json'
                if path.exists():
                    continue
                status(phase='steering', source_id=s, request_type=rtype, done=len(list((out / 'units').glob('*.json'))), total=2 * len(sources))
                h = H[s]
                ids = {k: v for k, v in prompts(h, rtype).items() if k in ('B', 'C')}
                base = read(out / 'baseline' / f'{s}.json')[rtype]
                base = {f: {k: v for k, v in base[f].items() if k != 'prompt_tokens'} for f in ('B', 'C')}
                gens, tf = steered_unit(e, ids, base, dirs['vectors'][s], steer_layer, cap, h, rtype)
                save_json(path, dict(unit_id=f'{s}_{rtype}', source_id=s, history_key=s, group='v21', request_type=rtype, inst_name=h['inst_name'],
                                     prompt_tokens={f: len(ids[f]) for f in ids}, generations=gens, teacher_forced=tf))
                if e.device == 'cuda':
                    torch.cuda.empty_cache()

        # ---- phase 5: open transfer units with this model's own assistant turns
        opens = rows(a.open_units)
        if a.smoke:
            opens = opens[:a.smoke]
        hist_path = out / 'open_histories.jsonl'
        regen = {r['history_key']: r for r in rows(hist_path)} if hist_path.exists() else {}
        full_mean = dirs['full_mean'][steer_layer]
        limit = e.spec['max_context'] - cap
        for i, u in enumerate(opens):
            path = out / 'open_units' / f"{u['unit_id']}.json"
            if path.exists():
                continue
            status(phase='open', unit_id=u['unit_id'], done=len(list((out / 'open_units').glob('*.json'))), total=len(opens))
            if u['history_key'] not in regen:
                history, terms = [], []
                for turn in u['user_turns']:
                    ids = e.prompt(history, turn, 'B')
                    if len(ids) > limit:
                        terms.append('context_limit')
                        break
                    g = e.generate(ids, cap)
                    terms.append(g['termination'])
                    history += [dict(role='user', content=turn), dict(role='assistant', content=e.text(g['token_ids']))]
                regen[u['history_key']] = dict(history_key=u['history_key'], history=history, terminations=terms)
                append(hist_path, regen[u['history_key']])
            rh = regen[u['history_key']]
            if 'context_limit' in rh['terminations']:
                save_json(path, dict(unit_id=u['unit_id'], pool=u['pool'], excluded='context_limit_during_history'))
                continue
            ids = {f: e.prompt(rh['history'], u['query'], f, u['serializer']) for f in ('B', 'C')}
            if max(len(x) for x in ids.values()) > limit:
                save_json(path, dict(unit_id=u['unit_id'], pool=u['pool'], excluded='context_limit_prompt', prompt_tokens={f: len(ids[f]) for f in ids}))
                continue
            base = {f: gen_record(e, e.generate(ids[f], cap)) for f in ('B', 'C')}
            g = torch.Generator().manual_seed(853 + i)
            r = torch.randn(full_mean.numel(), generator=g, dtype=torch.float64)
            vec = dict(mean=full_mean, random=(r / r.norm() * full_mean.double().norm()).float())
            gens, tf = steered_unit(e, ids, base, vec, steer_layer, cap)
            save_json(path, dict(unit_id=u['unit_id'], pool=u['pool'], group='open', history_key=u['history_key'], key=u['key'],
                                 history_terminations=rh['terminations'], prompt_tokens={f: len(ids[f]) for f in ids}, generations=gens, teacher_forced=tf))
            if e.device == 'cuda':
                torch.cuda.empty_cache()
        status(phase='completed', admitted=len(sources), units=len(list((out / 'units').glob('*.json'))),
               open_units=len(list((out / 'open_units').glob('*.json'))))
    except Exception:
        status(phase='failed', traceback=traceback.format_exc())
        raise


if __name__ == '__main__':
    main()
